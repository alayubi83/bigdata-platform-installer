#!/bin/bash

###############################################################################
#
# Big Data Platform Installer
#
# Common Library
#
###############################################################################

set -e
set -o pipefail

###############################################################################
# Color
###############################################################################

export RED="\033[0;31m"
export GREEN="\033[0;32m"
export YELLOW="\033[1;33m"
export BLUE="\033[0;34m"
export CYAN="\033[0;36m"
export MAGENTA="\033[0;35m"
export WHITE="\033[1;37m"
export NC="\033[0m"

###############################################################################
# Directory
###############################################################################

BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

LOG_DIR="${BASE_DIR}/logs"

mkdir -p "${LOG_DIR}"

LOG_FILE="${LOG_DIR}/install.log"

touch "${LOG_FILE}"

###############################################################################
# Banner
###############################################################################

banner(){

clear

echo -e "${CYAN}"

cat <<EOF

====================================================================

                 BIG DATA PLATFORM INSTALLER

====================================================================

EOF

echo -e "${NC}"

}

###############################################################################
# Logging
###############################################################################

timestamp(){

date +"%Y-%m-%d %H:%M:%S"

}

log(){

LEVEL="$1"

MESSAGE="$2"

printf "[%s] %-5s %s\n" \
"$(timestamp)" \
"${LEVEL}" \
"${MESSAGE}" | tee -a "${LOG_FILE}"

}

log_info(){

log INFO "$1"

}

log_warn(){

log WARN "$1"

}

log_error(){

log ERROR "$1"

}

log_success(){

log OK "$1"

}

###############################################################################
# Output
###############################################################################

info(){

echo -e "${BLUE}[INFO]${NC} $1"

}

warn(){

echo -e "${YELLOW}[WARN]${NC} $1"

}

error(){

echo -e "${RED}[ERROR]${NC} $1"

exit 1

}

success(){

echo -e "${GREEN}[ OK ]${NC} $1"

}

section(){

echo

echo -e "${MAGENTA}============================================================${NC}"

echo -e "${WHITE}$1${NC}"

echo -e "${MAGENTA}============================================================${NC}"

echo

}

###############################################################################
# Execute
###############################################################################

run(){

CMD="$*"

log_info "${CMD}"

eval "${CMD}"

RET=$?

if [ ${RET} -ne 0 ]; then

log_error "${CMD}"

exit ${RET}

fi

}

###############################################################################
# Retry
###############################################################################

retry(){

COUNT=0

MAX=5

CMD="$*"

until ${CMD}
do

COUNT=$((COUNT+1))

warn "Retry ${COUNT}/${MAX}"

sleep 3

if [ ${COUNT} -ge ${MAX} ]; then

error "Command failed."

fi

done

}

###############################################################################
# Check Command
###############################################################################

command_exists(){

command -v "$1" >/dev/null 2>&1

}

###############################################################################
# Check Root
###############################################################################

check_root(){

if [ "$EUID" -ne 0 ]; then

error "Run installer using sudo."

fi

}

###############################################################################
# Check Ubuntu
###############################################################################

check_ubuntu(){

if [ ! -f /etc/os-release ]; then

error "Unsupported Linux."

fi

. /etc/os-release

if [ "$ID" != "ubuntu" ]; then

error "Only Ubuntu supported."

fi

}
